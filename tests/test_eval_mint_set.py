"""The committed mint-set artifacts, checked for internal consistency.

`eval/instances/pool.json` is generated by a human-run fetch that touches the network;
everything downstream — the draw, the batch harness, the published composition — trusts
it. These tests never fetch. They assert *properties* of the committed bytes, and above
all that the file's **provenance header agrees with the records in the same file**.

That self-consistency framing is the point, and it is what makes the composition claim
non-circular. A header is a *claim* about how the pool was produced ("300 rows in, 166
survived, thresholds 15 and 2000"). If nothing checks it, the published table is just
typing. Checking the claim against the records beside it means a regeneration that
changes the pool but not the header — or the reverse — fails loudly rather than shipping
a number whose stated derivation no longer matches the data it describes.

Deliberately no literal counts. The pool is a *measurement*; asserting `166` here would
break on any legitimate refetch, and the next reader would "fix" it by editing the data.
The thresholds are compared to the module constants (a decision, not a measurement), and
the tier counts are compared to the records. `fetched_at` is provenance and is never
asserted on.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

import pytest

from eval.instances import tasks
from eval.instances.controls import (
    CONTROL_EXPECTATIONS,
    CONTROL_RECORDS,
    CONTROL_STEERING_SENTENCE,
)
from eval.instances.registry import (
    InstanceRecord,
    controls,
    dump_registry,
    load_header,
    load_registry,
    real,
)
from eval.instances.selection import (
    LARGE_REPOS,
    PURE_PYTHON_REPOS,
    InsufficientPoolError,
)
from eval.scripts.draw_mint_set import SEED, TARGET, build_selection
from eval.scripts.fetch_swebench_pool import (
    CONFIG,
    DATASET,
    MAX_CHANGED_LINES,
    MAX_STATEMENT_CHARS,
    SPLIT,
)

REPO_ROOT = Path(__file__).parent.parent
POOL = REPO_ROOT / "eval" / "instances" / "pool.json"
SELECTED = REPO_ROOT / "eval" / "instances" / "selected.json"
INSTANCES_DOC = REPO_ROOT / "eval" / "instances.md"

#: `owner/name`, anchored — the same shape `workspace.py` expands into a clone URL.
_SLUG = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]*/[A-Za-z0-9][A-Za-z0-9_.-]*$")

#: 65 drawn + 3 controls (D4). The pool must clear it with room for the small-repo
#: stratum to matter, not merely equal it.
LAUNCH_SIZE = 68


def test_committed_pool_loads_and_is_large_enough() -> None:
    """The committed pool parses as a registry and can supply the launched set."""
    records = load_registry(POOL)

    assert len(records) > LAUNCH_SIZE, (
        f"the committed pool has {len(records)} instances, which cannot comfortably "
        f"supply the {LAUNCH_SIZE}-instance launched set; a short pool is a short "
        f"denominator"
    )
    assert all(not record.is_control for record in records), (
        "pool.json holds fetched instances only; controls are hand-written and are "
        "appended to the selection, never drawn"
    )


def test_committed_pool_contains_only_allow_listed_repos() -> None:
    """Allow-list semantics survived the real fetch, not just the fixture."""
    repos = {record.repo for record in load_registry(POOL)}

    unexpected = repos - set(PURE_PYTHON_REPOS)
    assert not unexpected, (
        f"the committed pool contains repos outside PURE_PYTHON_REPOS: "
        f"{sorted(unexpected)}"
    )


def test_committed_pool_repos_are_slugs() -> None:
    """The Stage-1 bug, asserted a second time against the real data.

    `workspace.py` builds `https://github.com/{repo}.git`. A URL here double-prefixes and
    the clone fails at prep time, after a live batch has started spending. The fetch
    already refuses one; this is the guard on the artifact that is actually consumed.
    """
    for record in load_registry(POOL):
        assert _SLUG.match(record.repo), (
            f"{record.instance_id}: repo {record.repo!r} is not an 'owner/name' slug"
        )
        assert "://" not in record.repo
        assert "github.com" not in record.repo
        assert not record.repo.endswith(".git")


def test_committed_pool_header_carries_its_provenance() -> None:
    """The header identifies the dataset it came from and where it was fetched from."""
    header = load_header(POOL)

    assert header, (
        "pool.json has no provenance header: the pool would then be a bag of ids with "
        "no stated derivation, and the published composition would be unfalsifiable"
    )
    assert header["dataset"] == DATASET
    assert header["config"] == CONFIG
    assert header["split"] == SPLIT
    assert header["source_url"].startswith("https://")
    assert "fetched_at" in header
    # D2's honest fallback: the revision may be null if the surface reports none, but the
    # key must exist and the reason must be stated rather than the pin quietly dropped.
    assert "revision" in header
    assert header["revision_note"].strip()


def test_committed_pool_header_thresholds_are_the_module_constants() -> None:
    """The published thresholds are the ones the code applied, not numbers typed later."""
    filters = load_header(POOL)["filters"]

    assert filters["max_changed_lines"] == MAX_CHANGED_LINES
    assert filters["max_statement_chars"] == MAX_STATEMENT_CHARS
    assert filters["changed_line_rule"].strip(), (
        "D5's counting rule decides the pool and must be readable from the artifact by "
        "someone who does not run this code"
    )
    assert sorted(filters["pure_python_repos"]) == sorted(PURE_PYTHON_REPOS)


def test_committed_pool_header_counts_match_the_records() -> None:
    """The claim in the header is checked against the data beside it.

    `counts.short_statement` is the last tier, so it *is* the number of surviving
    records. The tiers are monotonically non-increasing by construction; if they are not,
    the header was not produced by the filters it describes.
    """
    header = load_header(POOL)
    records = load_registry(POOL)
    counts = header["counts"]

    assert set(counts) == {"all", "pure_python", "small_patch", "short_statement"}
    assert counts["short_statement"] == len(records), (
        f"header claims {counts['short_statement']} instances survived the filters but "
        f"the file carries {len(records)}; the header and the records disagree"
    )
    assert (
        counts["all"]
        >= counts["pure_python"]
        >= counts["small_patch"]
        >= counts["short_statement"]
    ), f"the tier counts are not monotonically non-increasing: {counts}"
    assert counts["all"] == header["num_rows_total"], (
        "every row the dataset reported must have entered the transform; a mismatch "
        "means the fetch paged short and the pool is drawn from part of the dataset"
    )


# --------------------------------------------------------------------------------------
# The three controls (D6). A control exists to detect *instrument error*: a flag raised on
# a control is, by construction, a false positive. That only holds if the control cannot
# fail for an innocent reason, so these tests check the properties that make it so —
# hand-written (not derived) tasks, no `tests/` path (the default A1 invariant is then
# unreachable), no shell or network action, and repos/commits that really exist.
# --------------------------------------------------------------------------------------

#: Words that would put a control's task outside the filesystem server: a shell turn can
#: trip an invariant, and a network turn is denied by the gate, so either one lets a
#: control fail for a reason that says nothing about the instrument.
_OFF_LIMITS_TASK_WORDS = (
    "shell",
    "bash",
    "terminal",
    "command",
    "execute",
    "run ",
    "pip",
    "install",
    "curl",
    "http://",
    "https://",
    "network",
    "git ",
)


def test_controls_are_marked_by_field_and_separable() -> None:
    """AC4. `controls()`/`real()` partition on the *field*, never on the id spelling.

    The decoy record's id contains "control" and its `is_control` is False: if the
    partition were ever "reimplemented" as a name check, that record would be misfiled as
    a control and the launched set would report 4 controls and 64 real instances — a
    silently wrong denominator, which is the whole failure mode `is_control` exists to
    prevent.
    """
    assert len(CONTROL_RECORDS) == 3, (
        f"D6 specifies exactly three controls, found {len(CONTROL_RECORDS)}"
    )
    assert all(record.is_control for record in CONTROL_RECORDS)

    decoy = InstanceRecord(
        instance_id="django__django-control-flow-11099",
        repo="django/django",
        base_commit="0" * 40,
        problem_statement="a real instance whose id merely contains the word control",
        task_string="Fix the following issue in this repository:\n\nsomething",
        is_control=False,
    )
    mixed = CONTROL_RECORDS + (decoy,)

    assert controls(mixed) == CONTROL_RECORDS
    assert real(mixed) == (decoy,)
    assert len(controls(mixed)) + len(real(mixed)) == len(mixed)


def test_control_ids_cannot_collide_with_a_drawn_instance() -> None:
    """`control__*` is a namespace no SWE-bench id uses, so no duplicate can arise."""
    pool_ids = {record.instance_id for record in load_registry(POOL)}

    for record in CONTROL_RECORDS:
        assert record.instance_id.startswith("control__")
        assert record.instance_id not in pool_ids
    assert len({record.instance_id for record in CONTROL_RECORDS}) == 3


def test_control_task_is_trivially_correct() -> None:
    """AC5. Each launched control's task is hand-written, filesystem-only, and cannot
    trip A1.

    The steering sentence names the forbidden actions ("run", "command") only to
    forbid them — saying "do not run any commands" cannot trip an invariant — so it is
    stripped before the off-limits scan rather than failing it.
    """
    for record in CONTROL_RECORDS:
        task = record.task_string

        assert not task.startswith(tasks.TASK_PREFIX), (
            f"{record.instance_id}: a control's task is hand-written; deriving it from a "
            f"problem statement would make its expected outcome a guess"
        )
        assert task.strip()
        assert "tests/" not in task, (
            f"{record.instance_id}: the task names a path under 'tests/', which is the "
            f"default A1 invariant — the control could then FAIL honestly and void the "
            f"mint"
        )
        checked = task.replace(CONTROL_STEERING_SENTENCE, "")
        lowered = checked.lower()
        for word in _OFF_LIMITS_TASK_WORDS:
            assert word not in lowered, (
                f"{record.instance_id}: task mentions {word!r}; controls are "
                f"filesystem-server-only so they cannot fail for an off-target reason"
            )

        expectation = CONTROL_EXPECTATIONS[record.instance_id]
        assert expectation["expected_verdict"].strip()
        assert expectation["expected_delta"].strip()
        assert expectation["rationale"].strip()
        assert expectation["expected_trajectory_verdict"].strip()
        assert expectation["trajectory_rationale"].strip()

    launched = {record.instance_id for record in CONTROL_RECORDS}
    assert set(CONTROL_EXPECTATIONS) >= launched
    held_out = set(CONTROL_EXPECTATIONS) - launched
    assert held_out == {"control__flask-verify-with-command"}, (
        "the only expectation without a launched record is the positive control, held "
        "out of CONTROL_RECORDS because it requires run_process — the launched "
        "composition is the successor mint's pre-registered decision "
        "(controls-rescope/composition-note.md)"
    )


def test_control_writes_are_new_root_level_files_only() -> None:
    """D6's hard rule: a control never edits an existing file, only adds a root-level one.

    An edit invites the model to improvise — reformat a neighbour, touch a second file —
    and every improvisation is an innocent-divergence vector under replay.
    """
    for record in CONTROL_RECORDS:
        expectation = CONTROL_EXPECTATIONS[record.instance_id]
        written = expectation["written_paths"]

        assert isinstance(written, tuple)
        for path in written:
            assert "/" not in path, (
                f"{record.instance_id}: control writes {path!r}, which is not at the "
                f"repository root"
            )
            assert path.startswith("BELAY_CONTROL"), (
                f"{record.instance_id}: control write {path!r} does not use the "
                f"collision-proof BELAY_CONTROL prefix"
            )
            assert path in record.task_string


def test_control_repos_and_commits_come_from_the_pool() -> None:
    """No invented commits: an invented commit fails at clone time and burns a live run.

    Each control's `(repo, base_commit)` is either a real pair in the committed pool, or
    the Stage-1 flask commit — which is not in the pool (its instance did not survive the
    filters) but is documented in `eval/instances.md` and has already been cloned and
    driven end-to-end for real.
    """
    pool_pairs = {(record.repo, record.base_commit) for record in load_registry(POOL)}
    doc = INSTANCES_DOC.read_text(encoding="utf-8")

    for record in CONTROL_RECORDS:
        assert record.repo in PURE_PYTHON_REPOS
        assert re.fullmatch(r"[0-9a-f]{40}", record.base_commit), (
            f"{record.instance_id}: base_commit {record.base_commit!r} is not a full sha"
        )
        in_pool = (record.repo, record.base_commit) in pool_pairs
        documented = record.base_commit in doc
        assert in_pool or documented, (
            f"{record.instance_id}: ({record.repo}, {record.base_commit}) is neither in "
            f"the committed pool nor documented in eval/instances.md"
        )


# --------------------------------------------------------------------------------------
# The draw (D4) and the committed `selected.json`. The draw fixes what the published
# number covers, so it must be a pure function of `(pool, target, seed)` and the committed
# artifact must be exactly what that function produces — checked byte-for-byte, which also
# pins the key order and the trailing newline.
# --------------------------------------------------------------------------------------


def test_draw_is_reproducible_from_seed(tmp_path: Path) -> None:
    """AC2, in its strongest form: the committed bytes are re-derivable, not just the ids.

    A weaker "the instance ids match" assertion would pass while the header drifted, and
    the header is where the seed, the composition and the control expectations live — the
    part of the file a reviewer would use to falsify the published number.
    """
    pool = load_registry(POOL)
    records, header = build_selection(pool)

    redrawn = tmp_path / "selected.json"
    dump_registry(records, redrawn, header=header)

    assert redrawn.read_bytes() == SELECTED.read_bytes(), (
        "re-running the draw from the committed pool did not reproduce the committed "
        "selected.json byte-for-byte; the seed, the target, the control set or the "
        "writer changed without the artifact being regenerated"
    )


def test_selected_registry_is_68_records_with_3_controls() -> None:
    """The launched set in one assertion: 65 drawn + 3 controls (D4, a decision).

    These are the only literal counts in this file, and they are here deliberately: they
    are choices, not measurements, so they *should* break loudly if someone changes them.
    """
    records = load_registry(SELECTED)

    assert len(records) == LAUNCH_SIZE
    assert len(real(records)) == TARGET
    assert controls(records) == CONTROL_RECORDS, (
        "the committed selection's controls are not the three in controls.py, in order"
    )
    assert records[: len(real(records))] == real(records), (
        "controls must be appended after the draw, not interleaved with it"
    )


def test_draw_composition_is_stratified() -> None:
    """AC3. The scarce diversity is never wasted and the top-up is balanced.

    No literal per-repo counts: a refetched pool may shift the small stratum by one or
    two, and hard-coding 28/19/18 here would be "fixed" by editing the data. The
    properties survive a regeneration; the numbers would not.
    """
    pool = load_registry(POOL)
    drawn = real(load_registry(SELECTED))
    drawn_ids = {record.instance_id for record in drawn}

    small_in_pool = {
        record.instance_id for record in pool if record.repo not in LARGE_REPOS
    }
    assert small_in_pool <= drawn_ids, (
        f"small-repo instances are the scarce diversity and none may be wasted; missing: "
        f"{sorted(small_in_pool - drawn_ids)}"
    )

    by_repo = Counter(record.repo for record in drawn)
    assert set(by_repo) <= set(PURE_PYTHON_REPOS)
    django, sympy = by_repo["django/django"], by_repo["sympy/sympy"]
    assert abs(django - sympy) <= 1, (
        f"the large-repo top-up is not balanced: django={django}, sympy={sympy}; the "
        f"dataset's 83% django+sympy concentration would then become the sample's"
    )


def test_published_composition_matches_the_records() -> None:
    """AC3's second half: the published table is generated from the file, not typed."""
    header = load_header(SELECTED)
    records = load_registry(SELECTED)
    composition = header["composition"]

    assert composition["launched"] == len(records)
    assert composition["real"] == len(real(records))
    assert composition["controls"] == len(controls(records))
    assert composition["by_repo"] == dict(
        sorted(Counter(record.repo for record in real(records)).items())
    ), (
        "the header's per-repo composition disagrees with the records beside it; the "
        "published composition would then be unfalsifiable typing"
    )


def test_selected_header_records_the_seed_and_its_history() -> None:
    """The seed is only honest if it was fixed before the draw was inspected.

    `seed_history` is the only defense against silent seed-shopping that survives review:
    a re-roll must leave the superseded seed and the reason in the committed file. An
    empty history is the claim "drawn once, never re-rolled" — and it is a claim someone
    can check against this file's git history.
    """
    header = load_header(SELECTED)

    assert header["seed"] == SEED
    assert header["target"] == TARGET
    assert header["control_count"] == len(CONTROL_RECORDS)
    assert header["seed_rationale"].strip()
    assert isinstance(header["seed_history"], list)
    for entry in header["seed_history"]:
        assert entry["seed"] != header["seed"]
        assert entry["reason"].strip(), "a superseded seed must carry its reason"
    assert header["source_pool"] == "eval/instances/pool.json"
    assert not Path(header["source_pool"]).is_absolute(), (
        "an absolute path in the header would not reproduce on another machine"
    )


def test_selected_header_publishes_the_control_expectations() -> None:
    """The controls' expected outcomes travel with the mint set, not in someone's head."""
    published = load_header(SELECTED)["controls"]

    assert set(published) == {record.instance_id for record in CONTROL_RECORDS}
    for instance_id, expectation in published.items():
        stated = CONTROL_EXPECTATIONS[instance_id]
        assert expectation["expected_verdict"] == stated["expected_verdict"]
        assert expectation["expected_delta"] == stated["expected_delta"]
        assert expectation["rationale"] == stated["rationale"]
        assert expectation["written_paths"] == list(stated["written_paths"]), (
            "JSON has no tuples; the published write set must round-trip as a list"
        )


def test_insufficient_pool_raises_rather_than_drawing_short() -> None:
    """AC6. A short draw is a short denominator — the R6 false-zero mode one layer up.

    Asserted against the real pool rather than a fabricated one, so it guards the exact
    call the draw script makes.
    """
    pool = load_registry(POOL)
    eligible = [record for record in pool if record.repo in PURE_PYTHON_REPOS]

    with pytest.raises(InsufficientPoolError):
        build_selection(pool, target=len(eligible) + 1)
